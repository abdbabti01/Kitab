// Generates the synthetic tokens the Identity Engineering Lab uses against /api/lab/identity/*. A fresh RSA key is
// generated, the tokens are signed with it, and ONLY the public key and the signed tokens are written out: the
// private key exists in this process's memory and is discarded, so nobody (Kitab included) can mint more.
// Run: node --experimental-strip-types scripts/identity-lab-fixtures.ts > src/identity/lab-fixtures.ts
import { generateKey, sign } from "../src/identity/jwt.ts";

const ISSUER = "https://idp.lab.kitab.example";
const AUDIENCE = "https://orders.lab.kitab.example";
const far = Date.UTC(2099, 0, 1) / 1000;
const issued = Date.UTC(2026, 10, 1) / 1000;

const key = await generateKey("lab-2026-11", "RS256");
const other = await generateKey("lab-2026-11", "RS256"); // same kid, different key: a forgery
const base = { iss: ISSUER, aud: AUDIENCE, iat: issued, exp: far, scope: "orders.read", synthetic: "Kitab lab token: grants nothing outside /api/lab/identity" };
const header = { alg: "RS256", typ: "at+jwt", kid: key.kid };
const tokens = {
  alice: await sign(header, { ...base, sub: "alice", tenant: "acme", jti: "lab-alice" }, key),
  aliceNoScope: await sign(header, { ...base, sub: "alice", tenant: "acme", scope: "profile", jti: "lab-alice-noscope" }, key),
  aliceOtherApi: await sign(header, { ...base, sub: "alice", tenant: "acme", aud: "https://hr.lab.kitab.example", jti: "lab-alice-hr" }, key),
  aliceExpired: await sign(header, { ...base, sub: "alice", tenant: "acme", exp: issued + 300, jti: "lab-alice-expired" }, key),
  dave: await sign(header, { ...base, sub: "dave", tenant: "globex", jti: "lab-dave" }, key),
  forged: await sign(header, { ...base, sub: "alice", tenant: "acme", scope: "orders.read orders.delete", jti: "lab-forged" }, other),
};

console.log(`// GENERATED by scripts/identity-lab-fixtures.ts. Synthetic: public key and pre-signed tokens only; the private
// key was discarded at generation, so no further tokens can be minted. These tokens grant nothing anywhere except
// Kitab's teaching endpoints under /api/lab/identity, which return fixed synthetic data.
export const LAB_ISSUER = ${JSON.stringify(ISSUER)};
export const LAB_AUDIENCE = ${JSON.stringify(AUDIENCE)};
export const LAB_JWK = ${JSON.stringify(key.publicJwk)} as const;
export const LAB_TOKENS = ${JSON.stringify(tokens, null, 2)} as const;`);
