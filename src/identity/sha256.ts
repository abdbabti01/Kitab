// SHA-256 and base64url, synchronous, so the protocol engine can compute real PKCE challenges (RFC 7636 §4.2:
// BASE64URL(SHA256(ASCII(code_verifier)))) while staying pure and deterministic. Tests check it against node:crypto
// and RFC 7636 Appendix B. Not used for anything secret: Web Crypto does the real signing in jwt.ts.
// ponytail: plain FIPS 180-4 loop, fine for the short strings the engine hashes.

